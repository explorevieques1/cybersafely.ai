#!/usr/bin/env python3
"""Generate Full Calendar event notes from .claude/hooks/deadlines.tsv plus the contract's recurring meetings.

Re-run any time deadlines.tsv changes:  python3 .claude/scripts/sync-calendar.py
Only files with `generated: true` in their frontmatter are replaced; events you add by hand are never touched.
Times are US Eastern (contract times), stored as Full Calendar "floating" local times.
"""
from pathlib import Path

VAULT = Path(__file__).resolve().parents[2]
TSV = VAULT / ".claude/hooks/deadlines.tsv"
CAL = VAULT / "Calendar"
TERM_START, TERM_END = "2026-10-01", "2026-12-29"

# folder -> deadline kinds it holds
FOLDERS = {"Deadlines": {"contract", "info"}, "Goals": {"goal", "build"}}

RECURRING = [
    # title, days (Full Calendar letters: U M T W R F S), start, end
    ("1:1 with Torino", ["M"], "12:00", "12:30"),
    ("CyberSafely team meeting", ["T"], "12:00", "13:00"),
    ("1:1 with Torino", ["R"], "13:00", "13:30"),
    ("Time report due 5 PM", ["W"], "16:30", "17:00"),
    ("Social plan due 12 PM", ["F"], "11:30", "12:00"),
    # Prep blocks (my own scheduling, not contract commitments)
    ("Check-in prep", ["M"], "11:00", "11:30"),
    ("Check-in prep", ["R"], "12:00", "12:30"),
    ("Time report prep", ["W"], "15:00", "16:30"),
    ("Social plan draft", ["F"], "09:30", "11:30"),
]
DAY_NAMES = {"M": "Mon", "T": "Tue", "W": "Wed", "R": "Thu", "F": "Fri"}


def safe(name: str) -> str:
    return "".join(c for c in name if c not in '\\/:*?"<>|#^[]').strip()[:80]


def is_generated(path: Path) -> bool:
    try:
        head = path.read_text(encoding="utf-8")[:400]
    except OSError:
        return False
    return "generated: true" in head


def clear_generated(folder: Path) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    for p in folder.glob("*.md"):
        if is_generated(p):
            p.unlink()


def write(folder: Path, filename: str, frontmatter: dict, body: str = "") -> None:
    lines = ["---"]
    for k, v in frontmatter.items():
        if isinstance(v, list):
            lines.append(f"{k}: [{', '.join(v)}]")
        elif isinstance(v, bool):
            lines.append(f"{k}: {'true' if v else 'false'}")
        else:
            lines.append(f'{k}: "{v}"' if isinstance(v, str) else f"{k}: {v}")
    lines += ["generated: true", "---", body]
    (folder / f"{safe(filename)}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    # Recurring meetings and due times
    work = CAL / "Work"
    clear_generated(work)
    for title, days, start, end in RECURRING:
        label = "+".join(DAY_NAMES[d] for d in days)
        write(work, f"({label}) {title}", {
            "title": title, "allDay": False, "type": "recurring", "daysOfWeek": days,
            "startTime": start, "endTime": end, "startRecur": TERM_START, "endRecur": TERM_END,
        }, "Contract cadence (times are US Eastern). Generated by .claude/scripts/sync-calendar.py.")

    # Deadlines and goals from the TSV
    for folder_name in FOLDERS:
        clear_generated(CAL / folder_name)
    count = 0
    for line in TSV.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 4:
            continue
        date, kind, outcome, text = parts[0], parts[1], parts[2], parts[3]
        folder_name = next((f for f, kinds in FOLDERS.items() if kind in kinds), None)
        if not folder_name:
            continue
        prefix = "" if outcome in ("all", "build") else f"[{outcome}] "
        title = prefix + text
        write(CAL / folder_name, f"{date} {title}", {
            "title": title, "allDay": True, "type": "single", "date": date,
            "kind": kind, "outcome": outcome,
        }, "Generated from .claude/hooks/deadlines.tsv. Edit that file, then re-run sync-calendar.py.")
        count += 1
    print(f"Calendar synced: {len(RECURRING)} recurring events, {count} dated milestones.")


if __name__ == "__main__":
    main()
