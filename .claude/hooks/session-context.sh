#!/usr/bin/env bash
# SessionStart hook: prints today's contract context. Claude Code adds stdout to the session context.
# Times are Puerto Rico local (AST, UTC-4 all year). Contract times are US Eastern.
set -u
VAULT="$(cd "$(dirname "$0")/../.." && pwd)"
export TZ=America/Puerto_Rico

today=$(date +%F)
start=2026-10-01
day=$(( ( $(date -d "$today" +%s) - $(date -d "$start" +%s) ) / 86400 + 1 ))
dow=$(date +%A)

echo "## Session context (auto-generated by .claude/hooks/session-context.sh)"
echo "- Today: $dow $today (Puerto Rico time)."
if (( day < 1 )); then
  echo "- Contract starts Thu Oct 1, 2026 (in $(( 1 - day )) day(s))."
elif (( day <= 90 )); then
  echo "- Contract day $day of 90 (Oct 1 – Dec 29, 2026)."
else
  echo "- 90-day term complete (ended Dec 29, 2026)."
fi
if [[ "$today" < "2026-11-01" ]]; then
  echo "- Clock: Eastern = Puerto Rico time right now."
else
  echo "- Clock: Puerto Rico is 1 h ahead of Eastern (EST). Contract times in ET → add 1 h."
fi

# Recurring items for today (only during the contract term)
(( day >= 1 && day <= 90 )) && case "$dow" in
  Monday)    echo "- Today: 1:1 with Torino 12:00–12:30 PM ET. Have the check-in ready." ;;
  Tuesday)   echo "- Today: team meeting 12:00–1:00 PM ET." ;;
  Wednesday) echo "- Today: TIME REPORT due to Torino by 5:00 PM ET. Check-in draft for Thursday's 1:1." ;;
  Thursday)  echo "- Today: 1:1 with Torino 1:00–1:30 PM ET. Draft next week's social plan tonight." ;;
  Friday)    echo "- Today: NEXT WEEK'S SOCIAL PLAN due by 12:00 PM ET." ;;
esac

# Deadlines in the next 7 days
horizon=$(date -d "$today +7 days" +%F)
echo "- Deadlines and milestones through $horizon:"
found=0
while IFS=$'\t' read -r d kind outcome text; do
  [[ -z "${d:-}" || "$d" == \#* ]] && continue
  if [[ ! "$d" < "$today" && ! "$d" > "$horizon" ]]; then
    echo "  - $d [$kind · $outcome] $text"
    found=1
  fi
done < "$VAULT/.claude/hooks/deadlines.tsv"
(( found )) || echo "  - none"

# Today's daily note
note="$VAULT/Daily/$today.md"
if [[ -f "$note" ]]; then
  echo "- Today's daily note: Daily/$today.md (first 60 lines below)"
  echo '```markdown'
  head -n 60 "$note"
  echo '```'
else
  echo "- No daily note yet for today (Daily/$today.md). /evening-plan creates tomorrow's."
fi
exit 0
